// Fetches the TheMealDB catalog and writes supabase/seed.sql with the dinner-eligible recipes.
//
//   node scripts/mealdb/import.mjs                  # fetch from the API (MEALDB_API_KEY, default "1")
//   node scripts/mealdb/import.mjs --input all.json # reuse a previously saved array of raw meals
//
// Re-run after changing normalize.mjs, then `npm run db:reset`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { EXCLUDED } from './exclude.mjs';
import { meatIngredients, normalizeMeal } from './normalize.mjs';
import { DIET_OVERRIDES } from './overrides.mjs';

const COLUMNS = {
  source_id: 'text', title: 'text', category: 'text', dish_type: 'text', country: 'text', tags: 'text[]',
  image_url: 'text', youtube_url: 'text', source_url: 'text', ingredients: 'jsonb', steps: 'jsonb',
  ingredient_names: 'text[]', allergens: 'text[]', diet_flags: 'text[]', swaps: 'jsonb',
};

async function fetchAll() {
  const key = process.env.MEALDB_API_KEY || '1';
  const meals = new Map();
  for (const letter of 'abcdefghijklmnopqrstuvwxyz0123456789') {
    const res = await fetch(`https://www.themealdb.com/api/json/v1/${key}/search.php?f=${letter}`);
    if (!res.ok) throw new Error(`TheMealDB ${letter}: HTTP ${res.status}`);
    for (const meal of (await res.json()).meals ?? []) meals.set(meal.idMeal, meal);
  }
  return [...meals.values()];
}

const inputIdx = process.argv.indexOf('--input');
const raw = inputIdx > -1 ? JSON.parse(readFileSync(process.argv[inputIdx + 1], 'utf8')) : await fetchAll();

const known = new Set(raw.map((m) => m.idMeal));
const unknown = [...EXCLUDED.keys()].filter((id) => !known.has(id));
if (unknown.length) throw new Error(`exclude.mjs lists ids that are not in the catalog: ${unknown.join(', ')}`);

const missingOverrides = [...DIET_OVERRIDES.keys()].filter((id) => !known.has(id));
if (missingOverrides.length) throw new Error(`overrides.mjs lists ids that are not in the catalog: ${missingOverrides.join(', ')}`);

const recipes = raw
  .filter((meal) => !EXCLUDED.has(meal.idMeal))
  .map(normalizeMeal)
  .filter(Boolean).sort((a, b) => Number(a.source_id) - Number(b.source_id));
// Invariant: nothing may be flagged vegetarian while an ingredient names meat, unless it is a swappable stock.
for (const r of recipes.filter((r) => r.diet_flags.includes('vegetarian'))) {
  const meat = meatIngredients(r.ingredient_names).filter((n) => !r.swaps.some((w) => w.from === n));
  if (meat.length) throw new Error(`${r.title} is flagged vegetarian but lists ${meat.join(', ')}`);
}
if (recipes.length < 100) throw new Error(`Only ${recipes.length} usable recipes; refusing to write seed.sql`);

const json = JSON.stringify(recipes);
if (json.includes('$seed$')) throw new Error('Recipe data contains the SQL quote tag');

const columnList = Object.keys(COLUMNS).join(', ');
const columnDefs = Object.entries(COLUMNS).map(([c, t]) => `${c} ${t}`).join(', ');
const updates = Object.keys(COLUMNS).filter((c) => c !== 'source_id').map((c) => `${c} = excluded.${c}`).join(', ');

const sql = `-- GENERATED by scripts/mealdb/import.mjs. Do not edit by hand.
-- ${recipes.length} dinner recipes from TheMealDB (https://www.themealdb.com).
insert into public.recipes (${columnList})
select ${columnList}
from jsonb_to_recordset($seed$${json}$seed$::jsonb) as r(${columnDefs})
on conflict (source_id) do update set ${updates};
`;

writeFileSync(fileURLToPath(new URL('../../supabase/seed.sql', import.meta.url)), sql);
console.log(`Wrote ${recipes.length} of ${raw.length} meals to supabase/seed.sql (${(sql.length / 1e6).toFixed(1)} MB), ${EXCLUDED.size} editorially excluded`);
